<?php
namespace TT\Tests\Php;

use TT\Infrastructure\Tenancy\CurrentClub;
use TT\Modules\CustomCss\DesignSystem\TokenCatalogue;
use TT\Modules\CustomCss\VisualEditor;
use WP_UnitTestCase;

/**
 * #4839 — migration 0314 regenerates the stylesheet every academy already
 * saved from the visual editor, with the rule that skips untouched fields.
 *
 * Rows are written and read with $wpdb directly: the migration writes SQL,
 * and the config services keep a per-request cache that would hide it.
 */
final class VisualEditorRegenerateMigrationTest extends WP_UnitTestCase {

    private const MIGRATION = '/database/migrations/0314_visual_editor_regenerate_css.php';

    /** What the editor wrote before #4839 for a save that changed only the line colour. */
    private const OLD_CSS = "/* Generated by TalentTrack visual editor (#0064 / #0075). */\n\n.tt-root {\n    --tt-primary: #0b3d2e;\n    --tt-success: #00a32a;\n    --tt-line: #cccccc;\n    --tt-muted: #5b6e75;\n    --tt-r-md: 8px;\n}\n";

    private function put( int $club, string $key, string $value ): void {
        global $wpdb;
        $wpdb->replace( $wpdb->prefix . 'tt_config', [
            'club_id'      => $club,
            'config_key'   => $key,
            'config_value' => $value,
        ] );
    }

    private function css( int $club, string $surface ): string {
        global $wpdb;
        return (string) $wpdb->get_var( $wpdb->prepare(
            "SELECT config_value FROM {$wpdb->prefix}tt_config WHERE club_id = %d AND config_key = %s",
            $club, "custom_css.{$surface}.css"
        ) );
    }

    /**
     * Every field as an untouched pre-#4839 form posted it, plus one real
     * change: the line colour.
     *
     * @return array<string, string>
     */
    private function oneChange(): array {
        $settings = [];
        foreach ( TokenCatalogue::all() as $key => $def ) {
            $settings[ $key ] = (string) ( $def['legacy_default'] ?? $def['default'] );
        }
        $settings['line_color'] = '#cccccc';
        return $settings;
    }

    private function seedVisual( int $club, string $surface ): void {
        $this->put( $club, "custom_css.{$surface}.css", self::OLD_CSS );
        $this->put( $club, "custom_css.{$surface}.visual_settings", (string) wp_json_encode( $this->oneChange() ) );
    }

    private function runMigration(): void {
        ( require dirname( __DIR__, 2 ) . self::MIGRATION )->up();
    }

    public function test_a_real_change_is_kept_and_everything_else_follows_tokens_css(): void {
        $club = CurrentClub::id();
        $this->seedVisual( $club, 'frontend' );

        $this->runMigration();

        $css = $this->css( $club, 'frontend' );
        $this->assertSame( VisualEditor::generateCss( $this->oneChange() ), $css );
        $this->assertStringContainsString( "    --tt-line: #cccccc;\n", $css, 'the changed line is written exactly as before' );
        $this->assertSame( 1, preg_match_all( '/--tt-[a-z0-9-]+\s*:/', $css ), 'no other token is written' );
        $this->assertStringNotContainsString( 'box-shadow:', $css );
    }

    public function test_a_second_run_changes_nothing(): void {
        $club = CurrentClub::id();
        $this->seedVisual( $club, 'frontend' );

        $this->runMigration();
        $first = $this->css( $club, 'frontend' );
        $this->runMigration();

        $this->assertSame( $first, $this->css( $club, 'frontend' ) );
    }

    public function test_hand_written_css_is_left_alone(): void {
        $club = CurrentClub::id();
        $hand = ".tt-root { --tt-line: #e5e7ea; --tt-muted: #5b6e75; }\n";
        $this->put( $club, 'custom_css.admin.css', $hand );
        $this->put( $club, 'custom_css.admin.visual_settings', '' );

        $this->runMigration();

        $this->assertSame( $hand, $this->css( $club, 'admin' ) );
    }

    public function test_every_club_is_regenerated(): void {
        $other = CurrentClub::id() + 1;
        $this->seedVisual( $other, 'frontend' );

        $this->runMigration();

        $this->assertSame( VisualEditor::generateCss( $this->oneChange() ), $this->css( $other, 'frontend' ) );
    }
}
